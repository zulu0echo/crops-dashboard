// Writes docs/seed-review.md: every unreviewed rating of 2 or 3 with its re-check command,
// straight from the data, so the reviewer checklist cannot drift from what is published.
//   node scripts/review-list.mjs
import { writeFileSync } from 'node:fs';
import { loadData } from './rollup.mjs';

const { criteria, providers } = loadData('data');
const byId = Object.fromEntries(criteria.criteria.map((c) => [c.id, c]));
const out = ['# Review checklist', '', 'Generated by `node scripts/review-list.mjs` from `data/providers/*.yaml`. Do not edit by hand.', '',
  'Every unreviewed rating of 2 or 3, with the command that reproduces it. Run it, compare with the finding, then set the cell\'s',
  '`review` to `{status: reviewed, by: <your name>, date: <YYYY-MM-DD>}` in the provider file. Ratings of 2 or 3 need two reviewers (methodology 2.8);',
  'record the second in the pull request. Also skim every finding marked "Judgment call".', ''];
let n = 0;
for (const p of providers) {
  const rows = Object.entries(p.scores).filter(([, c]) => c.score >= 2 && c.review?.status !== 'reviewed');
  if (!rows.length) continue;
  out.push(`## ${p.name} (\`data/providers/${p.slug}.yaml\`)`, '');
  for (const [id, c] of rows) {
    const cmds = (c.evidence ?? []).filter((e) => e.recheck).map((e) => `\`${e.recheck.replace(/`/g, "'")}\``);
    out.push(`- [ ] **${id} ${byId[id].short} = ${c.score}.** ${cmds.join(' ; ') || 'No recheck command recorded (CI should have rejected this).'}`);
    n++;
  }
  out.push('');
}
if (!n) out.push('Nothing awaiting review.');
writeFileSync('docs/seed-review.md', out.join('\n') + '\n');
console.log(`wrote docs/seed-review.md (${n} ratings to review)`);
